#!/bin/sh
# Regenerates the TEST-ONLY TLS material for the RFB test servers (docker/README.md):
#
#   test-ca.pem           self-signed CA ("rfb2 TEST-ONLY CA"); clients trust this for the X509* types
#   test-ca-key.pem       its private key
#   test-server.pem       server certificate signed by the CA: CN localhost, SAN DNS:localhost,
#                         IP:127.0.0.1, IP:::1; used by TigerVNC for X509None / X509Vnc / X509Plain
#   test-server-key.pem   its RSA 2048 private key; TigerVNC also uses it as the RSA-AES (RA2*) key
#
# Everything is valid for 100 years. The private keys are committed and therefore public: never use
# any of this outside these test containers.
#
#   sh docker/certs/make-certs.sh       (OpenSSL >= 1.1.1; set OPENSSL=/path/to/openssl to override)
set -eu

cd "$(dirname "$0")"
openssl=${OPENSSL:-openssl}
days=36500
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

header() {
  cat <<EOF
TEST-ONLY: generated by docker/certs/make-certs.sh for the node-rfb2 test servers.
This key material is committed to a public repository: it is NOT secret. Never trust it,
or use it, anywhere except the local RFB test containers.
EOF
}

$openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$tmp/ca-key.pem" 2>/dev/null
$openssl req -x509 -new -key "$tmp/ca-key.pem" -sha256 -days $days -out "$tmp/ca.pem" \
  -subj "/O=node-rfb2 tests/CN=rfb2 TEST-ONLY CA" \
  -addext "basicConstraints=critical,CA:TRUE" \
  -addext "keyUsage=critical,keyCertSign,cRLSign" \
  -addext "subjectKeyIdentifier=hash"

$openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$tmp/server-key.pem" 2>/dev/null
$openssl req -new -key "$tmp/server-key.pem" -out "$tmp/server.csr" \
  -subj "/O=node-rfb2 tests/CN=localhost"
cat > "$tmp/server.ext" <<'EOF'
basicConstraints=critical,CA:FALSE
keyUsage=critical,digitalSignature,keyEncipherment
extendedKeyUsage=serverAuth
subjectAltName=DNS:localhost,IP:127.0.0.1,IP:::1
subjectKeyIdentifier=hash
authorityKeyIdentifier=keyid
EOF
$openssl x509 -req -in "$tmp/server.csr" -CA "$tmp/ca.pem" -CAkey "$tmp/ca-key.pem" \
  -set_serial 0x$($openssl rand -hex 8) -sha256 -days $days -extfile "$tmp/server.ext" \
  -out "$tmp/server.pem" 2>/dev/null

$openssl verify -CAfile "$tmp/ca.pem" "$tmp/server.pem" >/dev/null

for f in ca ca-key server server-key; do
  { header; echo; cat "$tmp/$f.pem"; } > "test-$f.pem"
done
chmod 644 test-*.pem
$openssl x509 -in test-server.pem -noout -subject -issuer -enddate -ext subjectAltName
